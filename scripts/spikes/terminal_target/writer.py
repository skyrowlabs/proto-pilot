"""The write guard, for the terminal target's five paths.

A deliberate mirror of `protopilot/files.py` rather than a call into it: that
module's `WRITABLE` is the web tree's five paths and is a module constant, so
there is no seam to pass a different list through. Widening `files.WRITABLE`
to make the spike work would be building Phase 2's `target` axis inside Phase
1, which is the one thing the gate must not do.

**That reason expired on 2026-09-04.** Phase 2 landed the seam: `files.py` now
takes `writable`/`protected` as arguments and the lists live on the target
module. This file is kept unchanged anyway, because it is spike material that
`docs/TODO/terminal-target.md` Phase 6 deletes -- not because the constraint it
describes is still true.

The guarantee is the same one and it is the reason this exists at all: model
output is data, not authority. Everything the model returns is checked against
the allowlist before it touches disk, and the check is done for every file
before any file is written -- a half-applied pass leaves a tree that is neither
the old one nor the new one, and the repair loop would then be debugging a
state no pass ever intended to produce.
"""

from __future__ import annotations

import fnmatch
from pathlib import Path
from typing import List, Sequence, Tuple

from protopilot.files import GeneratedFile, UnsafePath
from scripts.spikes.terminal_target.brief import PROTECTED, WRITABLE

BANNER_PY = "# GENERATED by proto-pilot ({pass_name} pass). Regenerated whole; do not hand-edit.\n"
BANNER_CSS = "/* GENERATED by proto-pilot ({pass_name} pass). Regenerated whole; do not hand-edit. */\n"


def check_path(path: str, writable: Sequence[str] = WRITABLE, protected: Sequence[str] = PROTECTED) -> Path:
    """Normalise and authorise one model-supplied path."""
    if not path or path.startswith("/") or "\\" in path:
        raise UnsafePath(f"absolute or malformed path: {path!r}")
    rel = Path(path)
    if ".." in rel.parts:
        raise UnsafePath(f"path escapes the project: {path!r}")
    posix = rel.as_posix()
    if posix in protected:
        raise UnsafePath(f"{posix} is part of the skeleton and is not generated")
    if not any(fnmatch.fnmatch(posix, pattern) for pattern in writable):
        raise UnsafePath(f"{posix} is not a generated path; generated paths are: {', '.join(writable)}")
    return rel


def banner_for(path: str, pass_name: str) -> str:
    return (BANNER_CSS if path.endswith(".tcss") else BANNER_PY).format(pass_name=pass_name)


def write_all(project_dir: Path, files: List[GeneratedFile], pass_name: str) -> List[Path]:
    """Authorise every path first, then write. All-or-nothing."""
    checked: List[Tuple[Path, GeneratedFile]] = [(check_path(f.path), f) for f in files]
    written: List[Path] = []
    for rel, generated in checked:
        dest = project_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        body = generated.content
        if "GENERATED by proto-pilot" not in body.split("\n", 3)[0]:
            body = banner_for(generated.path, pass_name) + body
        if not body.endswith("\n"):
            body += "\n"
        dest.write_text(body)
        written.append(rel)
    return written
