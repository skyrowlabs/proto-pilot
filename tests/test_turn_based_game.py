"""The second archetype, and the proof that the axis is real.

`crud` was an extraction — it could not tell us whether the design worked,
because it was the design's starting point. This one is the test: a shape whose
pages are a board and a history, generated by replacing every baseline
generator, needing nothing the skeleton does not already ship.

The load-bearing test here is `test_the_generated_game_passes_its_own_suite`,
and inside that the generated suite's own `test_playing_to_a_win_shows_the_result`.
Everything else would pass against a static picture of a board.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

from protopilot import archetypes
from protopilot.archetypes import turn_based_game as tbg
from protopilot.build import generate
from protopilot.llm import OfflineLLM
from protopilot.passes import PassContext
from protopilot.render import TOKEN_RE, render_skeleton
from protopilot.spec import Screen, Spec, checkable_paths

# Host-side: no key, no Docker daemon, no network. The offline baseline is
# what makes the whole pipeline testable under one marker.
pytestmark = pytest.mark.unit

pytest.importorskip("fastapi")
pytest.importorskip("sqlalchemy")


@pytest.fixture()
def game_spec() -> Spec:
    spec = Spec(
        name="Kitten TTT",
        slug="kitten_ttt",
        purpose="Two players take turns.",
        archetype="turn-based-game",
        port=8099,
    )
    spec.screens = [Screen(**s) for s in tbg.screens(spec)]
    return spec


@pytest.fixture()
def game_tree(game_spec, tmp_path) -> Path:
    render_skeleton(game_spec, tmp_path)
    game_spec.save(tmp_path)
    generate(game_spec, PassContext(project_dir=tmp_path), OfflineLLM(), log=lambda _: None)
    return tmp_path


# ── the shape ────────────────────────────────────────────────────────────


def test_it_is_registered_by_existing():
    assert "turn-based-game" in archetypes.names()


def test_its_screens_are_not_the_crud_spread(game_spec):
    """The whole reason the axis exists. You do not fill in a form to make a
    move, so there is no `form` screen — and `crud.screens()` cannot say that."""
    kinds = {s["kind"] for s in tbg.screens(game_spec)}
    assert "form" not in kinds
    assert "/board" in {s["path"] for s in tbg.screens(game_spec)}


def test_it_replaces_every_baseline_generator(game_spec):
    """A board cannot be built by the CRUD generators, so this archetype
    overrides all five. `crud` overrides none. Those are the two ends."""
    for kind in ("models_py", "seed_py", "routes_py", "smoke_py", "templates_for"):
        assert archetypes.generator(game_spec, kind) is not None, f"{kind} is not overridden"


def test_it_declares_no_assets():
    """It needs nothing the skeleton does not ship — which is exactly why it is
    the second archetype and `simulator` is not."""
    assert tbg.ASSETS == ()


def test_a_broken_extra_falls_back_to_a_playable_board():
    """`spec.extra` can be empty, partial, or hand-edited nonsense. All three
    answer the same way: a playable default beats a traceback at generation."""
    for extra in ({}, {"width": "wide"}, {"width": 999}, {"pieces": []}):
        spec = Spec(name="X", slug="x", purpose="p", archetype="turn-based-game", extra=extra)
        board = tbg.board_of(spec)
        assert board.width >= 2 and board.height >= 2


def test_extra_is_honoured_when_it_is_valid():
    spec = Spec(name="X", slug="x", purpose="p", archetype="turn-based-game", extra={"width": 7, "height": 6})
    board = tbg.board_of(spec)
    assert (board.width, board.height) == (7, 6)


# ── what it generates ────────────────────────────────────────────────────


def test_no_placeholder_survives(game_tree):
    for path in game_tree.rglob("*"):
        if path.is_file() and path.suffix in {".py", ".html", ".yml", ".css", ".md", ".txt"}:
            assert not TOKEN_RE.search(path.read_text()), f"{path} kept a placeholder"


def test_it_generates_a_board_page_and_no_form_template(game_tree):
    templates = {p.name for p in (game_tree / "app" / "templates").glob("*.html")}
    assert "board.html" in templates
    assert not any(name.endswith("_form.html") for name in templates)


def test_the_pieces_are_drawn_not_lettered(game_tree):
    """The prompt insists artwork is drawn rather than emoji, and the offline
    baseline has to hold the same line — it is the worked example the prompt is
    written against."""
    board = (game_tree / "app" / "templates" / "board.html").read_text()
    assert "<svg" in board
    assert "<line" in board and "<circle" in board


def test_every_checkable_path_is_served(game_tree):
    """The browser stage fetches these. A screen the spec names and no route
    serves is a 404 reported as a broken page."""
    import re

    served = {
        p.replace("{row_id}", "1")
        for p in re.findall(r'@router\.get\("([^"]+)"', (game_tree / "app" / "routes.py").read_text())
    }
    unserved = set(checkable_paths(Spec.load(game_tree))) - served
    assert not unserved, f"checkable but served by nothing: {sorted(unserved)}"


def test_the_generated_suite_tests_a_win_not_just_a_200(game_tree):
    """The assertion that separates a game from a picture of one. If this test
    ever disappears from the generator, the suite goes on passing."""
    suite = (game_tree / "tests" / "test_smoke.py").read_text()
    assert "def test_playing_to_a_win_shows_the_result" in suite
    assert "def test_playing_a_square_changes_the_board" in suite


def test_the_generated_game_passes_its_own_suite(game_tree):
    """The whole point. Generated models, routes, templates, seed and win
    detection, exercised by the suite the pipeline wrote for them."""
    env = {
        **os.environ,
        "DATABASE_URL": f"sqlite:///{game_tree / 'dev.db'}",
        "APP_NAME": "Kitten TTT",
        "APP_PURPOSE": "Two players take turns.",
        "PYTHONDONTWRITEBYTECODE": "1",
    }
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider"],
        cwd=str(game_tree),
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_the_seed_puts_the_playable_game_last(game_tree):
    """Order is load-bearing and was wrong once: the board page shows the most
    recent match, so seeding the finished game second opened the app on a
    finished board where every move was refused — which looks exactly like a
    broken game."""
    seed = (game_tree / "app" / "seed.py").read_text()
    finished_at = seed.index("finished=True")
    open_at = seed.index("finished=False")
    assert finished_at < open_at, "the in-progress game must be seeded last"


# ── the same shape, in a terminal ────────────────────────────────────────
#
# Phase 6 of `docs/TODO/terminal-target.md`. Completing this pair was not
# optional once `tui` became `targets.DEFAULT`: a hole in the default target is
# `proto new` refusing its own classifier's answer, which is a worse failure
# than any stated hole elsewhere in the matrix.


@pytest.fixture()
def tui_game_spec(game_spec) -> Spec:
    game_spec.target = "tui"
    return game_spec


@pytest.fixture()
def tui_game_tree(tui_game_spec, tmp_path) -> Path:
    render_skeleton(tui_game_spec, tmp_path)
    tui_game_spec.save(tmp_path)
    generate(tui_game_spec, PassContext(project_dir=tmp_path), OfflineLLM(), log=lambda _: None)
    return tmp_path


def test_the_two_medium_neutral_generators_are_shared(tui_game_spec):
    """`models_py` and `seed_py` are asked for under the SAME name by both
    targets, because both are pure SQLAlchemy and neither knows whether a route
    or a screen will read it. A second copy would drift the first time either
    medium changed a column."""
    from protopilot import archetypes

    for kind in ("models_py", "seed_py"):
        assert archetypes.generator(tui_game_spec, kind) is getattr(tbg, kind)


def test_it_replaces_the_three_generators_that_are_medium_specific(tui_game_spec):
    from protopilot import archetypes

    for kind in ("tui_screens_py", "tui_smoke_py", "tui_tcss"):
        assert archetypes.generator(tui_game_spec, kind) is not None, f"no terminal {kind} for a board game"


def test_the_board_is_a_grid_of_buttons_not_a_table(tui_game_tree, tui_game_spec):
    """The terminal fragment's whole instruction. A `DataTable` of squares
    would render and would not be playable."""
    screens = (tui_game_tree / "app" / "screens.py").read_text()
    assert 'Grid(id="board")' in screens
    assert 'Button(EMPTY, id=f"cell-{index}")' in screens

    styles = (tui_game_tree / "app" / "app.tcss").read_text()
    board = tbg.board_of(tui_game_spec)
    assert f"grid-size: {board.width} {board.height}" in styles, "a Grid with no grid-size is a column"


def test_the_generated_suite_plays_a_game_rather_than_looking_at_one(tui_game_tree):
    suite = (tui_game_tree / "tests" / "test_smoke.py").read_text()
    assert "async def test_playing_to_a_win_shows_the_result" in suite
    assert "async def test_playing_a_square_changes_the_board" in suite
    assert "pilot.click" in suite, "nothing in the suite presses a square"


def test_the_terminal_game_passes_its_own_suite(tui_game_tree):
    """The load-bearing one, and the second half of the archetype x target
    matrix. No key, no Docker, no browser, no port -- the whole matrix is now
    four baselines and every one of them runs in this suite."""
    result = subprocess.run(  # noqa: S603
        [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider", "tests/"],
        cwd=str(tui_game_tree),
        env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"},
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert result.returncode == 0, f"the generated terminal game is red:\n{result.stdout}\n{result.stderr}"


def test_the_terminal_game_verifies_green(tui_game_tree, tui_game_spec):
    """Through the real verifier, including the blank-screen check. A board
    drawn as nine buttons that never got their labels would pass a suite that
    only queried the database."""
    from protopilot.targets import tui as tui_target

    result = tui_target.verifier(tui_game_tree, tui_game_spec).verify()
    assert result.ok, f"{result.stage}: {result.summary}\n{result.output}"
