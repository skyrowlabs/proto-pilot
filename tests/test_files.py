from __future__ import annotations

import pytest

from protopilot.files import GeneratedFile, UnsafePath, check_path, write_all
from protopilot.targets import web as web_target

# Host-side: no key, no Docker daemon, no network. The offline baseline is
# what makes the whole pipeline testable under one marker.
pytestmark = pytest.mark.unit

# The guard is mechanism; the lists belong to the target. Read off the target
# module rather than restated here -- a second copy of the allowlist in the test
# that guards the allowlist would agree with itself and prove nothing.
WRITABLE = web_target.WRITABLE
PROTECTED = web_target.PROTECTED


@pytest.mark.parametrize(
    "path", ["app/models.py", "app/routes.py", "app/seed.py", "app/templates/trips_list.html", "tests/test_smoke.py"]
)
def test_generated_paths_are_allowed(path):
    assert check_path(path, WRITABLE, PROTECTED)


@pytest.mark.parametrize(
    "path",
    [
        "/etc/passwd",
        "../../etc/passwd",
        "app/../../escape.py",
        "Dockerfile",
        "compose.yml",
        "app/main.py",
        "app/db.py",
        "tests/conftest.py",
        "app/templates/base.html",
    ],
)
def test_skeleton_and_escapes_are_refused(path):
    # Model output is data, not authority. The parts of the tree that are known
    # to work are the parts the model must not be able to touch.
    with pytest.raises(UnsafePath):
        check_path(path, WRITABLE, PROTECTED)


def test_write_all_is_all_or_nothing(tmp_path):
    files = [
        GeneratedFile("app/models.py", "x = 1\n"),
        GeneratedFile("Dockerfile", "FROM scratch\n"),
    ]
    with pytest.raises(UnsafePath):
        write_all(tmp_path, files, "schema", WRITABLE, PROTECTED)
    # The legal file must not have landed either: a half-applied pass leaves a
    # tree no pass intended to produce.
    assert not (tmp_path / "app" / "models.py").exists()


def test_banner_is_added_once(tmp_path):
    write_all(tmp_path, [GeneratedFile("app/models.py", "x = 1\n")], "schema", WRITABLE, PROTECTED)
    first = (tmp_path / "app" / "models.py").read_text()
    assert first.startswith("# GENERATED by proto-pilot (schema pass)")

    write_all(tmp_path, [GeneratedFile("app/models.py", first)], "schema", WRITABLE, PROTECTED)
    second = (tmp_path / "app" / "models.py").read_text()
    assert second.count("GENERATED by proto-pilot") == 1
