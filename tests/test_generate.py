"""The generated tree IS the test.

proto-pilot has no way to assert that a prompt produced good code. What it can
assert is that the whole pipeline -- skeleton, five passes, write guard --
produces a tree whose own smoke suite passes. The offline baseline is what
makes that runnable in CI, with no API key and no Docker daemon.

The suite is run against SQLite rather than Postgres for the same reason: it
exercises the generated models, routes, templates, seed and form coercion,
which is where generation bugs live. Postgres-specific behaviour is not what
these files get wrong.
"""

from __future__ import annotations

import ast
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from protopilot.build import generate
from protopilot.llm import OfflineLLM
from protopilot.passes import PassContext
from protopilot.render import TOKEN_RE, render_skeleton

# Host-side: no key, no Docker daemon, no network. The offline baseline is
# what makes the whole pipeline testable under one marker.
pytestmark = pytest.mark.unit

pytest.importorskip("fastapi")
pytest.importorskip("sqlalchemy")
jinja2 = pytest.importorskip("jinja2")

GENERATED = (
    "app/models.py",
    "app/routes.py",
    "app/seed.py",
    "tests/test_smoke.py",
)


@pytest.fixture()
def tree(spec, tmp_path) -> Path:
    render_skeleton(spec, tmp_path)
    spec.save(tmp_path)
    generate(spec, PassContext(project_dir=tmp_path), OfflineLLM(), log=lambda _: None)
    return tmp_path


def test_no_placeholder_survives_generation(tree):
    for path in tree.rglob("*"):
        if path.is_file() and path.suffix in {".py", ".html", ".yml", ".css", ".md", ".txt"}:
            assert not TOKEN_RE.search(path.read_text()), f"{path} kept a placeholder"


def test_every_python_file_parses(tree):
    for path in tree.rglob("*.py"):
        ast.parse(path.read_text(), str(path))


def test_every_template_parses(tree):
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(tree / "app" / "templates")))
    for path in (tree / "app" / "templates").glob("*.html"):
        env.parse(path.read_text(), filename=str(path))


def test_generated_files_carry_a_banner(tree):
    for rel in GENERATED:
        assert "GENERATED by proto-pilot" in (tree / rel).read_text().split("\n", 2)[0]


def test_skeleton_files_were_not_touched(tree):
    for rel in (
        "Dockerfile",
        "compose.yml",
        "app/main.py",
        "app/db.py",
        "app/templates/base.html",
        "tests/conftest.py",
    ):
        assert "GENERATED by proto-pilot" not in (tree / rel).read_text()


def test_every_template_a_route_renders_exists(tree):
    """A template name invented in routes.py is a 500 at render time, and the
    only place it shows up before then is right here."""
    source = (tree / "app" / "routes.py").read_text()
    names = {
        node.args[1].value
        for node in ast.walk(ast.parse(source))
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "TemplateResponse"
        and len(node.args) > 1
        and isinstance(node.args[1], ast.Constant)
    }
    assert names
    for name in names:
        assert (tree / "app" / "templates" / name).exists(), f"routes.py renders missing {name}"


def test_the_generated_app_passes_its_own_smoke_suite(tree):
    env = {
        **os.environ,
        "DATABASE_URL": f"sqlite:///{tree / 'dev.db'}",
        "APP_NAME": "Gear List",
        "APP_PURPOSE": "Track camping gear across trips.",
        "PYTHONDONTWRITEBYTECODE": "1",
    }
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider"],
        cwd=str(tree),
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr


# ── screens the spec asked for, that are not CRUD ───────────────────────
#
# The standing gap this closes: the baseline re-derived a CRUD set from
# `spec.entities` and ignored `spec.screens`, so a screen that was not a list,
# a form or a record got a route from the model path and nothing from this one.
# `checkable_paths()` still handed the path to the browser stage, which fetched
# a 404 and reported the screen as broken.


@pytest.fixture()
def tree_with_a_custom_screen(spec, tmp_path) -> Path:
    from protopilot.archetypes import crud
    from protopilot.spec import Screen

    spec.screens = [Screen(**s) for s in crud.screens(spec)]
    spec.screens.append(Screen(name="Packing board", path="/board", kind="custom"))
    render_skeleton(spec, tmp_path)
    spec.save(tmp_path)
    generate(spec, PassContext(project_dir=tmp_path), OfflineLLM(), log=lambda _: None)
    return tmp_path


def test_a_custom_screen_gets_a_route_and_a_template(tree_with_a_custom_screen):
    tree = tree_with_a_custom_screen
    assert '@router.get("/board"' in (tree / "app" / "routes.py").read_text()
    assert (tree / "app" / "templates" / "board.html").exists()


def test_a_custom_screen_gets_a_smoke_test(tree_with_a_custom_screen):
    """Generated before the route, from the spec — so a screen the generator
    forgot is a red test rather than a silent omission."""
    assert "def test_board_renders" in (tree_with_a_custom_screen / "tests" / "test_smoke.py").read_text()


def _served_paths(tree: Path) -> set[str]:
    """Every path routes.py registers, with `{row_id}` filled the way the
    browser stage fills it — so the two sets are directly comparable."""
    decorated = re.findall(r'@router\.(?:get|post)\("([^"]+)"', (tree / "app" / "routes.py").read_text())
    return {p.replace("{row_id}", "1") for p in decorated}


def test_every_checkable_path_is_actually_served(tree_with_a_custom_screen):
    """The exact shape of the old bug: the browser stage is handed a list of
    paths to fetch, and one of them was served by nothing."""
    from protopilot.spec import Spec, checkable_paths

    tree = tree_with_a_custom_screen
    wanted = set(checkable_paths(Spec.load(tree)))
    unserved = wanted - _served_paths(tree)

    assert not unserved, f"checkable but served by nothing: {sorted(unserved)}"
    assert "/board" in wanted, "the custom screen is not even being checked"


def test_the_served_path_check_would_catch_a_missing_route(tree_with_a_custom_screen):
    """A gate nobody has seen fail is a gate nobody knows works. Delete the
    custom screen's route and the check must go red."""
    tree = tree_with_a_custom_screen
    routes = tree / "app" / "routes.py"
    routes.write_text(routes.read_text().replace('@router.get("/board"', '@router.get("/gone"'))

    assert "/board" not in _served_paths(tree)


