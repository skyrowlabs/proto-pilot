"""The write guard.

Model output is data, not authority. Every file the model produces is checked
against an allowlist of paths before it touches the disk, so a pass that
decides it would rather rewrite the Dockerfile simply cannot. The skeleton is
the part we know works; making it unwritable is what keeps that true.

**The mechanism is here; the list is not.** Which five paths are generated
depends on which tree is being generated into, so `WRITABLE` and `PROTECTED`
live on the target module (`protopilot/targets/web.py`) and are handed in.
They were moved rather than copied: a default value here would be a second
definition of "the default target", and it would be the one that quietly
applied the web allowlist to a terminal tree.
"""

from __future__ import annotations

import fnmatch
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

#: The banner, in each comment syntax a generated file can be written in.
#:
#: Keyed by suffix rather than by target: which languages exist is a property
#: of the files, and a `.tcss` stylesheet fenced behind a `#` comment is a
#: parse error whichever medium asked for it. `banner_for` falls back to the
#: Python form, which is right for every generated path that is not one of
#: these two.
BANNER_PY = "# GENERATED by proto-pilot ({pass_name} pass). Regenerated whole; do not hand-edit.\n"
BANNER_HTML = "{{# GENERATED by proto-pilot ({pass_name} pass). Regenerated whole; do not hand-edit. #}}\n"
BANNER_CSS = "/* GENERATED by proto-pilot ({pass_name} pass). Regenerated whole; do not hand-edit. */\n"

BANNERS = {".html": BANNER_HTML, ".css": BANNER_CSS, ".tcss": BANNER_CSS}


class UnsafePath(ValueError):
    """Raised when a pass tries to write somewhere it is not allowed to."""


@dataclass(frozen=True)
class GeneratedFile:
    """One file a pass returned: where it wants to go, and what is in it.

    Deliberately no `rel()` helper. It returned `Path(self.path)` and had no
    callers left once path handling moved to `check_path`, which normalises and
    authorises in the same step -- so a second, unauthorised way to turn a
    model-supplied string into a path was sitting next to the one that checks
    it. Nothing was calling the wrong one; something eventually would have.
    """

    path: str
    content: str


def check_path(path: str, writable: Sequence[str], protected: Sequence[str] = ()) -> Path:
    """Normalise and authorise one model-supplied path against one target's lists.

    `writable` and `protected` are arguments rather than module constants
    because they are the running target's -- see the module docstring.
    """
    if not path or path.startswith("/") or "\\" in path:
        raise UnsafePath(f"absolute or malformed path: {path!r}")
    rel = Path(path)
    if ".." in rel.parts:
        raise UnsafePath(f"path escapes the project: {path!r}")
    posix = rel.as_posix()
    if posix in protected:
        raise UnsafePath(f"{posix} is part of the skeleton and is not generated")
    if not any(fnmatch.fnmatch(posix, pattern) for pattern in writable):
        raise UnsafePath(f"{posix} is not a generated path; generated paths are: {', '.join(writable)}")
    return rel


def banner_for(path: str, pass_name: str) -> str:
    suffix = Path(path).suffix
    return BANNERS.get(suffix, BANNER_PY).format(pass_name=pass_name)


def write_all(
    project_dir: Path,
    files: list[GeneratedFile],
    pass_name: str,
    writable: Sequence[str],
    protected: Sequence[str] = (),
) -> list[Path]:
    """Authorise every path first, then write. All-or-nothing.

    Validating up front matters: a half-applied pass leaves a tree that is
    neither the old one nor the new one, and the repair loop would then be
    debugging a state no pass ever intended to produce.
    """
    checked = [(check_path(f.path, writable, protected), f) for f in files]
    written: list[Path] = []
    for rel, generated in checked:
        dest = project_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        body = generated.content
        banner = banner_for(generated.path, pass_name)
        if "GENERATED by proto-pilot" not in body.split("\n", 3)[0]:
            body = banner + body
        if not body.endswith("\n"):
            body += "\n"
        dest.write_text(body)
        written.append(rel)
    return written
